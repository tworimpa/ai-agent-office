import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';

// Studio and Desktop also run without Node. Ship this reproducible ES module in the wheel.
const root = fileURLToPath(new URL('../', import.meta.url));
const notices = [];
for (const name of ['beautiful-mermaid', '@dagrejs/dagre', '@dagrejs/graphlib']) {
  const file = new URL('../node_modules/' + name + '/LICENSE', import.meta.url);
  notices.push(name + '\n' + (await readFile(file, 'utf8')).replaceAll('\r\n', '\n').trim());
}
await build({
  absWorkingDir: root,
  stdin: {contents: "export {renderMermaid} from 'beautiful-mermaid';", resolveDir: root},
  outfile: 'src/agent_office/web/mermaid-flow-renderer.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  lineLimit: 120,
  banner: {js: '/*! Generated by npm run build:flow.\n\n' + notices.join('\n\n') + '\n*/'},
});
